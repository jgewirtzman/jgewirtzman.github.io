"""Build _publications.md from the CV's citations.bib (Quarto pre-render step).

Lists published work and preprints only. Entries tagged `review` in the CV
appear only if they have a DOI (a public preprint); submitted manuscripts
without one are left out, and the journal they are under review at is never shown.
"""
import html
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
CANDIDATES = [
    os.environ.get("CV_DIR", ""),
    os.path.join(SITE, "cv"),  # checked out here by the GitHub workflow
    os.path.join(os.path.dirname(SITE), "jgewirtzman-cv"),  # local sibling checkout
]
OUT = os.path.join(SITE, "_publications.md")
SCHOLAR = "https://scholar.google.com/citations?hl=en&user=1uVeNjEAAAAJ"
ME = "Gewirtzman"
MAX_AUTHORS = 8

# Preprint servers by DOI prefix.
SERVERS = {
    "10.22541/": "ESS Open Archive",
    "10.21203/": "Research Square",
    "10.2139/": "SSRN",
    "10.1101/": "bioRxiv",
    "10.64898/": "bioRxiv",
    "10.31223/": "EarthArXiv",
    "10.31220/": "agriRxiv",
    "10.5194/essd-2": "Earth System Science Data Discussions",
}


def find_bib():
    for d in CANDIDATES:
        if d and os.path.exists(os.path.join(d, "citations.bib")):
            return os.path.join(d, "citations.bib")
    sys.exit("publications.py: citations.bib not found (set CV_DIR)")


def load(bib):
    cmd = ["quarto", "pandoc", "-f", "biblatex", "-t", "csljson", bib]
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def tex(s):
    """Tidy the bits of LaTeX that pandoc leaves in titles and names."""
    s = re.sub(r"\$_\{?([^}$]*)\}?\$", r"<sub>\1</sub>", s)
    s = re.sub(r"\$\^\{?\\dagger\}?\$|\^\\dagger", "†", s)
    s = re.sub(r"\$\^\{?([^}$]*)\}?\$", r"<sup>\1</sup>", s)
    s = re.sub(r"<i>([a-z])", lambda m: "<i>" + m.group(1).upper(), s)  # genus names
    return s.replace("$", "")


def name(a):
    if "literal" in a:
        return "et al." if a["literal"] == "others" else tex(a["literal"])
    given = a.get("given", "")
    parts = [p for p in re.split(r"[\s.]+", given) if p.strip("-")]
    initials = "".join("-".join(q[0] + "." for q in p.split("-") if q) for p in parts)
    n = f"{tex(a['family'])}, {initials}".strip(", ")
    return f"**{n}**" if ME in a["family"] else n


def authors(lst):
    names = [name(a) for a in lst]
    etal = names and names[-1] == "et al."
    if etal:
        names = names[:-1]
    if len(names) > MAX_AUTHORS:
        mine = next((i for i, n in enumerate(names) if ME in n), None)
        shown = names[:MAX_AUTHORS - 1]
        if mine is not None and mine >= MAX_AUTHORS - 1:
            shown += ["…", names[mine]]
        names, etal = shown, True
    return ", ".join(names) + (", et al." if etal else "")


def server(doi):
    return next((v for k, v in SERVERS.items() if doi.startswith(k)), "Preprint")


def entry(e, kind):
    year = e["issued"]["date-parts"][0][0]
    title = tex(e["title"]).rstrip(".")
    doi = e.get("DOI", "")
    url = f"https://doi.org/{doi}" if doi else e.get("URL", "")
    venue = e.get("container-title", "")
    if kind == "preprint":
        venue = f"Preprint, {server(doi)}"
    elif kind == "report":
        if venue.startswith("http"):
            url, venue = url or venue, ""
        venue = venue or e.get("publisher", "")
    elif kind == "chapter":
        venue = f"In *{venue}*" if venue else ""
    if kind == "article" and venue:
        venue = f"*{tex(venue)}*"
    if e.get("note", "").startswith("In press"):
        venue += ", in press"
    t = f"[{title}]({url})" if url else title
    end = "" if title[-1] in "?!" else "."
    parts = [f"{authors(e.get('author', []))} ({year}).", f"{t}{end}"]
    if venue:
        parts.append(f"{venue}.")
    return year, " ".join(parts), "contributed equally" in e.get("note", "")


def main():
    data = load(find_bib())
    groups = {"preprint": [], "article": [], "chapter": [], "report": []}
    for e in data:
        review = "review" in e.get("keyword", "").split(", ")
        if e["type"] == "chapter":
            kind = "chapter"
        elif e["type"] == "report":
            kind = "report"
        elif review:
            if not e.get("DOI"):
                continue  # submitted, not public
            kind = "preprint"
        else:
            kind = "article"
        groups[kind].append(entry(e, kind))

    out = [
        "<!-- Generated by _scripts/publications.py from the CV's citations.bib. Do not edit. -->",
        "",
        f"Also on [Google Scholar]({SCHOLAR}). † Authors contributed equally.",
        "",
    ]
    titles = {
        "preprint": "Preprints",
        "article": "Peer-Reviewed Publications",
        "chapter": "Book Chapters",
        "report": "Reports and Policy Briefings",
    }
    for kind, items in groups.items():
        if not items:
            continue
        items.sort(key=lambda x: -x[0])
        out += [f"## {titles[kind]}", "", '::: {.pubs}']
        year = None
        for y, text, _ in items:
            if kind == "article" and y != year:
                out += ["", f"### {y}", ""]
                year = y
            out.append(f"- {text}")
        out += [":::", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"publications.py: wrote {sum(map(len, groups.values()))} entries")


if __name__ == "__main__":
    main()
